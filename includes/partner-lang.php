/**
 * pt() — Partner Translation helper
 *
 * Returns the translated string for the given key based on the current language.
 * Falls back to the English translation, then to the key itself.
 *
 * @param  string $key  The English string (used as lookup key)
 * @return string       Translated string
 */
function pt(string $key): string {
    global $partnerLang;
    if (lang() === 'fr') {
        return $partnerLang['fr'][$key] ?? $partnerLang['en'][$key] ?? $key;
    }
    return $partnerLang['en'][$key] ?? $key;
}
